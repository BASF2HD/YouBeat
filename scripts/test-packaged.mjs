import { mkdtemp } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import os from 'node:os';
import path from 'node:path';
const binary = process.argv[2];
if (!binary) throw new Error('Pass the packaged executable path');
const profile = await mkdtemp(path.join(os.tmpdir(), 'youbeat-release-profile-'));
const child = spawn(binary, ['--desktop-self-test', '--test-profile=' + profile], { stdio: ['ignore','pipe','pipe'] });
let output = '';
child.stdout.on('data', data => { output += data; process.stdout.write(data); });
child.stderr.on('data', data => process.stderr.write(data));
const timer = setTimeout(() => child.kill(), 120000);
const status = await new Promise((resolve,reject) => { child.on('error',reject); child.on('exit',resolve); });
clearTimeout(timer);
if (status !== 0 || !output.includes('"ok":true')) throw new Error('Packaged YouBeat test failed (' + status + ')');
console.log('PASS: packaged YouBeat pipeline; isolated profile ' + profile);
